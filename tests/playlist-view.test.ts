import { describe, expect, it } from "vitest";
import fs from "node:fs";
import path from "node:path";
import {
  createAutoGeneratedTandaIndicator,
  shouldShowPlaylistUnsavedIndicator,
  matchesPlaylistFilter,
  resetPlaylistLastTandaState,
  resolvePlaylistWindowMs,
} from "../app/src/renderer/modules/playlist-view";

describe("playlist view helpers", () => {
  it("constructs the localized auto-generated tanda badge", () => {
    const attributes = new Map<string, string>();
    const element = {
      className: "", textContent: "", title: "",
      setAttribute: (key: string, value: string) => attributes.set(key, value),
      getAttribute: (key: string) => attributes.get(key) ?? null,
    } as unknown as HTMLSpanElement;
    const indicator = createAutoGeneratedTandaIndicator({
      label: "A",
      tooltip: "Review this generated tanda",
      document: { createElement: () => element } as unknown as Document,
    });
    expect(indicator.className).toBe("playlist-auto-generated-indicator");
    expect(indicator.textContent).toBe("A");
    expect(indicator.title).toBe("Review this generated tanda");
    expect(indicator.getAttribute("aria-label")).toBe("Review this generated tanda");
  });
  it("suppresses the unsaved pencil when the generated badge is shown", () => {
    expect(shouldShowPlaylistUnsavedIndicator({
      playlistUnsaved: true,
      autoGenerated: true,
    })).toBe(false);
    expect(shouldShowPlaylistUnsavedIndicator({
      playlistUnsaved: true,
      autoGenerated: false,
    })).toBe(true);
  });
  it("does not render internal legacy source paths in tanda summaries", () => {
    const renderer = fs.readFileSync(
      path.join(process.cwd(), "app/src/renderer/renderer.ts"),
      "utf8",
    );
    const styles = fs.readFileSync(
      path.join(process.cwd(), "app/src/renderer/styles.css"),
      "utf8",
    );
    expect(renderer).not.toContain('className = "tanda-legacy-source"');
    expect(styles).not.toContain(".tanda-legacy-source");
  });

  it("computes same-day playlist window", () => {
    const ms = resolvePlaylistWindowMs({
      startInput: "20:00",
      endInput: "23:00",
      defaultStartMinutes: 20 * 60,
      defaultEndMinutes: 3 * 60,
    });
    expect(ms).toBe(3 * 60 * 60 * 1000);
  });

  it("computes overnight playlist window", () => {
    const ms = resolvePlaylistWindowMs({
      startInput: "23:00",
      endInput: "02:00",
      defaultStartMinutes: 20 * 60,
      defaultEndMinutes: 3 * 60,
    });
    expect(ms).toBe(3 * 60 * 60 * 1000);
  });

  it("uses canonical orchestra matching for orchestra-chart playlist filters", () => {
    expect(
      matchesPlaylistFilter({
        filterText: "Francisco Canaro",
        orchestraFilter: "Francisco Canaro",
        fallbackText:
          "1938 - Edgardo Donato / Francisco Canaro Instrumental / Francisco Lomuto",
        canonicalArtists: ["Edgardo Donato", "Francisco Lomuto"],
      }),
    ).toBe(false);

    expect(
      matchesPlaylistFilter({
        filterText: "Francisco Canaro",
        orchestraFilter: "Francisco Canaro",
        fallbackText: "Canaro. Easy old faves - Francisco Canaro(3) - Sung",
        canonicalArtists: ["Francisco Canaro"],
      }),
    ).toBe(true);
  });

  it("clears the persisted last-tanda flag on startup", () => {
    const calls: Array<{ key: string; value: string }> = [];
    resetPlaylistLastTandaState(
      {
        setItem: (key, value) => {
          calls.push({ key, value });
        },
      },
      "tanda-playlist-current-last",
    );

    expect(calls).toEqual([
      { key: "tanda-playlist-current-last", value: "0" },
    ]);
  });
});
